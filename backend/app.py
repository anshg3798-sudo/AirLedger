BUDGET_LIMIT = 100


def pollution_budget(aqi):
    return {
        "safe_limit": BUDGET_LIMIT,
        "predicted": aqi,
        "exceeded": aqi > BUDGET_LIMIT,
        "overshoot": round(max(0, aqi - BUDGET_LIMIT), 1),
    }


def estimate(rows):
    bundle = models()
    frame = pd.DataFrame(rows, columns=FEATURES)
    aqi = bundle["regressor"].predict(frame).clip(0, 500).round(1)
    classifier = bundle["classifier"]
    return aqi, classifier.predict(frame), classifier


@app.get("/api/health")
def health():
    models()
    return jsonify(status="ok", message="AirLedger API running")


@app.post("/api/predict")
def predict():
    values = prediction_inputs(json_object())
    predictions, risks, classifier = estimate([values])
    aqi, risk = float(predictions[0]), int(risks[0])
    category, color = categorize_aqi(aqi)
    probabilities = classifier.predict_proba(pd.DataFrame([values], columns=FEATURES))[0]
    return jsonify(
        aqi=aqi, category=category, category_color=color,
        risk_level=risk, risk_label=RISK_LABELS[risk], risk_color=RISK_COLORS[risk],
        risk_probabilities={
            RISK_LABELS[int(label)]: round(float(probability) * 100, 1)
            for label, probability in zip(classifier.classes_, probabilities)
        },
        recommendations=get_recommendations(aqi),
        pollution_budget=pollution_budget(aqi),
    )


@app.route('/api/dashboard', methods=['GET'])
def dashboard():
    """Returns aggregated stats for the dashboard."""
    df = pd.read_csv(DATA_PATH)

    # Latest 60 distinct observation dates
    df['date'] = pd.to_datetime(df['date'])
    df = df.sort_values('date')
    recent = df.groupby('date', as_index=False)['aqi'].mean().tail(60)
    trend = [{'date': str(r['date'].date()), 'aqi': round(r['aqi'],1)}
             for _, r in recent.iterrows()]

    # Monthly averages (Jan–Dec)
    monthly = df.groupby('month')['aqi'].mean().round(1)
    month_names = ['Jan','Feb','Mar','Apr','May','Jun','Jul','Aug','Sep','Oct','Nov','Dec']
    monthly_data = [{'month': month_names[m-1], 'aqi': monthly.get(m, 0)}
                    for m in range(1, 13)]

    # Location averages
    loc_avg = df.groupby('location')['aqi'].mean().round(1).reset_index()
    location_data = [{'location': r['location'], 'aqi': r['aqi']} for _, r in loc_avg.iterrows()]

    # Risk distribution
    risk_counts = df['risk_level'].value_counts().sort_index()
    risk_data = [
        {'label': 'Safe',      'count': int(risk_counts.get(0, 0)), 'color': '#22c55e'},
        {'label': 'Moderate',  'count': int(risk_counts.get(1, 0)), 'color': '#f59e0b'},
        {'label': 'High Risk', 'count': int(risk_counts.get(2, 0)), 'color': '#ef4444'},
    ]

    # Summary stats
    stats = {
        'avg_aqi':       round(float(df['aqi'].mean()), 1),
        'max_aqi':       round(float(df['aqi'].max()), 1),
        'min_aqi':       round(float(df['aqi'].min()), 1),
        'high_risk_days': int((df['risk_level'] == 2).sum()),
        'safe_days':      int((df['risk_level'] == 0).sum()),
        'total_days':     len(df),
    }

    return jsonify({
        'trend':         trend,
        'monthly':       monthly_data,
        'by_location':   location_data,
        'risk_dist':     risk_data,
        'stats':         stats,
        'pollution_budget': {
            'safe_limit': BUDGET_LIMIT,
            'observations_exceeded': int(df['aqi'].gt(BUDGET_LIMIT).sum()),
        },
    })


