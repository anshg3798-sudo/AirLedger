from schema import FEATURES, InputError, number, prediction_inputs
from train import DATA_PATH, MODEL_PATH

app = Flask(__name__)
origins = [origin.strip() for origin in os.getenv(
    "AIRLEDGER_CORS_ORIGINS", "http://localhost:5173,http://127.0.0.1:5173"
).split(",") if origin.strip() and origin.strip() != "*"]
CORS(app, resources={r"/api/.*": {"origins": origins}}, allow_headers=["Content-Type"])


@lru_cache(maxsize=1)
def models():
    # Load only artifacts generated by this project's training command.
    try:
        return joblib.load(MODEL_PATH)
    except FileNotFoundError:
        abort(503, description="Model artifacts missing. Run python train.py.")


@app.errorhandler(HTTPException)
def http_error(error):
    return jsonify(error=error.description), error.code


@app.errorhandler(Exception)
def internal_error(error):
    app.logger.exception("Unhandled API error")
    return jsonify(error="An unexpected server error occurred"), 500


def json_object():
    if not request.is_json:
        abort(415, description="Send a JSON request with Content-Type application/json")
    data = request.get_json(silent=True)
    if not isinstance(data, dict):
        raise InputError("Request body must be a valid JSON object")
    return data


@app.errorhandler(InputError)
def invalid_input(error):
    return jsonify(error=str(error)), 400


RISK_LABELS = {0: "Safe", 1: "Moderate", 2: "High Risk"}
RISK_COLORS = {0: "#22c55e", 1: "#f59e0b", 2: "#ef4444"}

AQI_CATEGORIES = [
    (0,   50,  'Good',        '#22c55e'),
    (51,  100, 'Satisfactory','#84cc16'),
    (101, 200, 'Moderate',    '#f59e0b'),
    (201, 300, 'Poor',        '#f97316'),
    (301, 400, 'Very Poor',   '#ef4444'),
    (401, 500, 'Severe',      '#7c3aed'),
]

def categorize_aqi(aqi):
    for _, hi, label, color in AQI_CATEGORIES:
        if aqi <= hi:
            return label, color
    return 'Severe', '#7c3aed'

