@app.post("/api/forecast")
def forecast():
    """Simulate seven days using user-supplied baseline conditions."""
    data = json_object()
    defaults = {"base_pm25": 80, "base_temp": 25, "base_humidity": 55, "base_wind": 5}
    data = {**defaults, **data}
    base_pm25 = number(data, "base_pm25", (0, 400))
    base_temp = number(data, "base_temp", (-5, 50))
    base_humidity = number(data, "base_humidity", (0, 100))
    base_wind = number(data, "base_wind", (0, 40))
    # Older clients can supply a scenario month. Otherwise use the actual date's month.
    month = number(data, "month", (1, 12)) if "month" in data else None
    today = datetime.now(ZoneInfo("Asia/Kolkata")).date()
    dates = [today + timedelta(days=offset) for offset in range(1, 8)]
    rng = np.random.default_rng()
    rows = []
    for day in dates:
        pm25 = float(np.clip(base_pm25 + rng.normal(0, 15), 0, 400))
        rows.append({
            "pm25": pm25, "pm10": pm25 * 1.5, "no2": pm25 * 0.33,
            "so2": pm25 * 0.15, "co": pm25 * 0.022,
            "temperature": np.clip(base_temp + rng.normal(0, 1), -5, 50),
            "humidity": np.clip(base_humidity + rng.normal(0, 3), 0, 100),
            "wind_speed": np.clip(base_wind + rng.normal(0, 0.5), 0, 60),
            "rainfall": 0, "visibility": max(0.5, 10 - pm25 / 80),
            "month": day.month if month is None else month,
            "day_of_week": day.weekday(), "is_weekend": int(day.weekday() >= 5),
        })
    predictions, risks, _ = estimate(rows)
    forecasts = []
    for day, predicted, risk in zip(dates, predictions, risks):
        aqi = float(predicted)
        category, color = categorize_aqi(aqi)
        forecasts.append({
            "date": day.strftime("%a %b %d"), "iso_date": day.isoformat(), "aqi": aqi,
            "category": category, "color": color,
            "risk": RISK_LABELS[int(risk)], "risk_color": RISK_COLORS[int(risk)],
        })
    return jsonify(forecast=forecasts, mode="simulation")


